import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { hash } from '../scripts/build-theme.mjs';
import { installWindowCard, removeWindowCard } from '../scripts/window-card.mjs';
import * as cardInstaller from '../scripts/window-card.mjs';
import {applySession} from '../scripts/theme-session.mjs';

test('card install and removal preserve the existing profile and personal appearance', t => {
  const home = fs.mkdtempSync(path.join(os.tmpdir(), 'drokk-card-install-'));
  t.after(() => fs.rmSync(home, {recursive:true, force:true}));
  const write = (name, bytes) => {const file=path.join(home,name);fs.mkdirSync(path.dirname(file),{recursive:true});fs.writeFileSync(file,bytes);};
  const read = name => fs.readFileSync(path.join(home,name),'utf8');
  const original = {edits:[{path:'.config/example',before:'old',after:'new'}],settings:{}};
  write('.local/share/drokk/profile.json',JSON.stringify(original));
  write('.local/state/drokk/session.json',JSON.stringify({active:true}));
  write('.config/hypr/looknfeel.lua','-- personal config\n');
  write('bundle/drokk-card.so','fixture binary');
  write('bundle/build.json',JSON.stringify({hyprland:'0.56.1',binarySha256:hash('fixture binary')}));
  installWindowCard(home,path.join(home,'bundle'));
  assert.match(read('.config/hypr/looknfeel.lua'),/hl\.plugin\.load/);
  const installedName='drokk-card-'+hash('fixture binary')+'.so';
  assert.ok(read('.config/hypr/looknfeel.lua').includes(installedName));
  assert.equal(read('.local/share/drokk/window-card/'+installedName),'fixture binary');
  assert.equal(JSON.parse(read('.local/share/drokk/profile.json')).edits.length,2);
  installWindowCard(home,path.join(home,'bundle'));
  assert.equal(JSON.parse(read('.local/share/drokk/profile.json')).edits.length,2);
  const ownAppearance=read('.config/hypr/looknfeel.lua');
  const changedAppearance=ownAppearance.replace('-- BEGIN Drokk window card','-- BEGIN Drokk window card\n-- user change');
  assert.notEqual(changedAppearance,ownAppearance);
  write('.config/hypr/looknfeel.lua',changedAppearance);
  assert.throws(()=>installWindowCard(home,path.join(home,'bundle')),/edited/);
  assert.equal(read('.config/hypr/looknfeel.lua'),changedAppearance);
  write('.config/hypr/looknfeel.lua',ownAppearance);
  write('.config/hypr/looknfeel.lua',read('.config/hypr/looknfeel.lua')+'-- later edit\n');
  removeWindowCard(home);
  assert.equal(read('.config/hypr/looknfeel.lua'),'-- personal config\n-- later edit\n');
  assert.deepEqual(JSON.parse(read('.local/share/drokk/profile.json')),original);
  assert.equal(fs.existsSync(path.join(home,'.local/share/drokk/window-card')),false);
});

test('hyprpm card registration follows theme switching and removal leaves the manager binary alone', t=>{
  const home=fs.mkdtempSync(path.join(os.tmpdir(),'drokk-managed-card-'));
  t.after(()=>fs.rmSync(home,{recursive:true,force:true}));
  const write=(p,s)=>{const file=path.join(home,p);fs.mkdirSync(path.dirname(file),{recursive:true});fs.writeFileSync(file,s);};
  const read=p=>fs.readFileSync(path.join(home,p),'utf8');
  write('.local/share/drokk/profile.json',JSON.stringify({edits:[],settings:{}}));
  write('.local/state/drokk/session.json',JSON.stringify({active:true}));
  write('.config/hypr/looknfeel.lua','-- personal config\n');
  write('.config/omarchy/shell.json',JSON.stringify({plugins:[]}));
  write('manager/drokk-window-card.so','manager-owned binary');
  const binary=path.join(home,'manager/drokk-window-card.so');
  cardInstaller.registerManagedWindowCard(home,binary);
  cardInstaller.registerManagedWindowCard(home,binary);
  assert.equal(JSON.parse(read('.local/share/drokk/profile.json')).edits.length,1);
  assert.ok(read('.config/hypr/looknfeel.lua').includes(binary));
  assert.equal(fs.existsSync(path.join(home,'.local/share/drokk/window-card')),false,'no independent copy');
  const settings={read(){assert.fail('card must not change settings');},write(){assert.fail('card must not change settings');}};
  applySession(home,'dune',settings);
  assert.equal(read('.config/hypr/looknfeel.lua'),'-- personal config\n');
  applySession(home,'drokk',settings);
  cardInstaller.unregisterManagedWindowCard(home,binary);
  assert.equal(read('.config/hypr/looknfeel.lua'),'-- personal config\n');
  assert.equal(read('manager/drokk-window-card.so'),'manager-owned binary');
  assert.deepEqual(JSON.parse(read('.local/share/drokk/profile.json')).edits,[]);
});
